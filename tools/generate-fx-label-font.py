"""Small Arial Bold face matching the approved FX labels: CSS 10 px at 1.2x."""
from pathlib import Path
from PIL import ImageFont

root = Path(__file__).resolve().parents[1]
font = ImageFont.truetype('C:/Windows/Fonts/arialbd.ttf', 12)
ascent, descent = font.getmetrics()
bitmap = bytearray()
glyphs = ['{0,0,0,0,0,0}']
for code in range(ord('B'), ord('V') + 1):
    char = chr(code)
    x0, y0, x1, y1 = font.getbbox(char, anchor='ls')
    # Match the coverage of the browser's small DirectWrite labels. Linear
    # FreeType coverage makes the same Arial Bold outlines visibly thinner.
    values = [round(15 * (p / 255) ** .6) for p in font.getmask(char, 'L')]
    offset = len(bitmap)
    if len(values) % 2:
        values.append(0)
    bitmap.extend((values[i] << 4) | values[i + 1] for i in range(0, len(values), 2))
    glyphs.append('{%d,%d,%d,%d,%d,%d}' % (offset, round(font.getlength(char) * 16), x1 - x0, y1 - y0, x0, -y1))

output = '\n'.join([
    '#pragma once', '#include "lvgl.h"',
    '// Generated by tools/generate-fx-label-font.py; Arial Bold 12 px, B..V.',
    'namespace aurora_fx_skin {',
    'static const uint8_t label_bitmap[]={' + ','.join(map(str, bitmap)) + '};',
    'static const lv_font_fmt_txt_glyph_dsc_t label_glyphs[]={' + ','.join(glyphs) + '};',
    'static const lv_font_fmt_txt_cmap_t label_cmap[]={ {.range_start=66,.range_length=21,.glyph_id_start=1,.type=LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY} };',
    'static lv_font_fmt_txt_dsc_t label_dsc={.glyph_bitmap=label_bitmap,.glyph_dsc=label_glyphs,.cmaps=label_cmap,.cmap_num=1,.bpp=4,.bitmap_format=0};',
    f'static const lv_font_t label_font={{.get_glyph_dsc=lv_font_get_glyph_dsc_fmt_txt,.get_glyph_bitmap=lv_font_get_bitmap_fmt_txt,.line_height={ascent + descent},.base_line={descent},.dsc=&label_dsc}};',
    '}', ''
])
(root / 'main/aurora_fx_label12.h').write_text(output)
print(f'FX label glyphs: {len(bitmap)} bitmap bytes; line height {ascent + descent}')
