"""Fixed FIR coefficients: adjusting speed never computes trigonometry on audio task."""
from pathlib import Path
import math
tables=[]
for percent in [100]+list(range(101,126)):
 rows=[];cutoff=.94*min(1.,100/percent)
 for phase in range(64):
  values=[]
  for k in range(24):
   x=k-11-phase/64
   sinc=cutoff if abs(x)<1e-10 else math.sin(math.pi*cutoff*x)/(math.pi*x)
   window=.42-.5*math.cos(2*math.pi*k/23)+.08*math.cos(4*math.pi*k/23)
   values.append(sinc*window)
  total=sum(values);q=[round(v/total*32768) for v in values]
  q[11]+=32768-sum(q)
  assert sum(q)==32768 and max(q)<32768 and min(q)>=-32768
  rows.append('{'+','.join(map(str,q))+'}')
 tables.append('{\n'+',\n'.join(rows)+'\n}')
out=Path(__file__).resolve().parents[1]/'main/audio_speed_table.h'
out.write_text('#pragma once\n#include <stdint.h>\n// Generated by tools/generate-speed-table.py; Q15 unity gain, 24 taps, 64 phases.\nstatic const int16_t audio_speed_weights[26][64][24]={\n'+',\n'.join(tables)+'\n};\n',encoding='utf-8')
print('Speed coefficients: 79,872 flash bytes; no runtime table generation/allocation.')
