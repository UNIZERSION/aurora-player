#!/usr/bin/env python3
"""Generate matching Montserrat fallback glyphs; requires lv_font_conv 1.5.3.

Install the converter outside the firmware tree with npm install lv_font_conv@1.5.3,
then pass its node_modules/lv_font_conv/lv_font_conv.js path to --converter.
The checked-in TTF is the exact LVGL 9.3.0 built-in Montserrat-Medium source.
No system fonts or network access are used during generation.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess

PROJECT = Path(__file__).resolve().parents[1]
FONT = PROJECT / "tools/fonts/Montserrat-Medium.ttf"
FONT_SHA256 = "421f26b23e2be6b98373d32acd3cb2897b154d4bf0a77d26534ce476e4cbed53"
SIZES = (14, 16, 18, 20, 24, 32)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--converter", type=Path, required=True)
    parser.add_argument("--node", default="node")
    args = parser.parse_args()
    converter = args.converter.resolve()
    version = json.loads((converter.parent / "package.json").read_text())["version"]
    if version != "1.5.3":
        raise SystemExit(f"Expected lv_font_conv 1.5.3, found {version}")
    if hashlib.sha256(FONT.read_bytes()).hexdigest() != FONT_SHA256:
        raise SystemExit("Montserrat source hash mismatch")
    for size in SIZES:
        output = PROJECT / f"main/ui_montserrat_latin_{size}.c"
        command = [args.node, str(converter), "--no-compress", "--no-prefilter",
                   "--bpp", "4", "--size", str(size), "--font", str(FONT),
                   "-r", "0xA0-0x17F", "--format", "lvgl", "--lv-include",
                   "lvgl.h", "--force-fast-kern-format", "-o", str(output)]
        subprocess.run(command, check=True, cwd=PROJECT)
        generated = output.read_text(encoding="utf-8")
        # lv_font_conv writes absolute CLI paths into its header. Strip these
        # only from the comment so regeneration is byte-for-byte reproducible.
        options = (f"--no-compress --no-prefilter --bpp 4 --size {size} "
                   "--font tools/fonts/Montserrat-Medium.ttf -r 0xA0-0x17F "
                   "--format lvgl --lv-include lvgl.h --force-fast-kern-format "
                   f"-o main/ui_montserrat_latin_{size}.c")
        generated = re.sub(r"^ \* Opts:.*$", " * Opts: " + options,
                           generated, count=1, flags=re.MULTILINE)
        notice = ("/* Montserrat Project Authors, SIL OFL 1.1; see "
                  "licenses/Montserrat-OFL.txt.\n"
                  " * Generated by tools/generate_latin_fonts.py with lv_font_conv 1.5.3. */\n")
        output.write_text(notice + generated, encoding="utf-8", newline="\n")
        line_height = re.search(r"\.line_height = (\d+)", generated).group(1)
        base_line = re.search(r"\.base_line = (\d+)", generated).group(1)
        print(f"{output.name}: line_height={line_height}, base_line={base_line}")


if __name__ == "__main__":
    main()
