"""Generate original synthetic decoder smoke fixtures; requires FFmpeg 7+."""
from pathlib import Path
import argparse
import math
import struct
import subprocess
import tempfile
import wave

parser = argparse.ArgumentParser()
parser.add_argument("--ffmpeg", default="ffmpeg")
args = parser.parse_args()
project = Path(__file__).resolve().parent.parent
fixtures = project / "tests" / "fixtures"

with tempfile.TemporaryDirectory(prefix="tab5-codec-") as temporary:
    temp = Path(temporary)
    for name, rate, frames, channels in (("flac", 48000, 2048, 2), ("aac", 44100, 4096, 1)):
        source = temp / (name + ".wav")
        samples = bytearray()
        for frame in range(frames):
            for channel in range(channels):
                value = round((12000 if channel == 0 else 8000) * math.sin(2 * math.pi * (440 if channel == 0 else 880) * frame / rate))
                samples.extend(struct.pack("<h", value))
        with wave.open(str(source), "wb") as out:
            out.setnchannels(channels)
            out.setsampwidth(2)
            out.setframerate(rate)
            out.writeframes(samples)
        target = fixtures / ("selftest." + name)
        codec = ["-c:a", "flac", "-sample_fmt", "s32", "-bits_per_raw_sample", "24"] if name == "flac" else ["-c:a", "aac", "-profile:a", "aac_low", "-b:a", "64k", "-f", "adts"]
        subprocess.run([args.ffmpeg, "-v", "error", "-y", "-i", str(source), *codec, str(target)], check=True)
        if name == "flac":
            data = target.read_bytes()
            offset = 4
            while True:
                last = bool(data[offset] & 0x80)
                offset += 4 + int.from_bytes(data[offset + 1:offset + 4], "big")
                if last:
                    break
            data = data[:4] + bytes([0x80]) + data[5:42] + data[offset:]
            target.write_bytes(data)
        raw = subprocess.check_output([args.ffmpeg, "-v", "error", "-i", str(target), "-f", "s16le", "-"])
        values = struct.unpack("<" + "h" * (len(raw) // 2), raw)
        rms = math.sqrt(sum(v * v for v in values) / len(values))
        print(name, "encoded", target.stat().st_size, "decoded_frames", len(values) // channels, "rms", round(rms, 2))

header = ["/* Original synthetic tones generated by tests/generate_codec_fixtures.py. */", "#pragma once"]
for name in ("flac", "aac"):
    data = (fixtures / ("selftest." + name)).read_bytes()
    header.append(f"static const unsigned char codec_selftest_{name}[] = {{")
    header += ["    " + ",".join(f"0x{b:02x}" for b in data[pos:pos + 16]) + "," for pos in range(0, len(data), 16)]
    header.append("};")
(project / "main" / "codec_selftest_fixtures.h").write_text("\n".join(header) + "\n", encoding="ascii")
