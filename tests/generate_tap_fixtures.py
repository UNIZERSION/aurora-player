"""Generate tests/fixtures/tap_recordings.h from recorded BMI270 FIFO frames.

usage: python generate_tap_fixtures.py RAW400_BOOT0 RAW400_BOOT1 OUT.h

The inputs are decode_fifo.py raw400 CSVs (seg,idx,t_ms,x,y,z, 400 Hz frames,
4096 LSB/g) from the guided recording session of 2026-10-17 with the Tab5 on
its stand (lying almost flat, tilted ~9 degrees), as labelled in
tools/tap-eval/labels.csv. Each excerpt keeps the raw frames, so a test can
feed them at 400 Hz exactly as sleep_tap_input.cpp does, or derive 200 Hz.
"""
import csv
import sys

# name, boot, start_ms, end_ms, expected gesture (2, 3 or 0), comment
EXCERPTS = [
    # n1-a: the screen woke between its first and second tap (a touch), so
    # the firmware itself would have disarmed; as motion data it is a triple.
    ('triple_stand_music', 0, 731300, 734300, 3, 'n1-a: three taps on the stand, music playing'),
    ('triple_stand_lighter', 0, 744800, 747700, 3, 'n1-c: lighter triple across gravity, music playing'),
    ('double_stand', 0, 808000, 810600, 2, 'n2-a: double on the stand, paused'),
    ('double_side', 0, 812200, 814800, 2, 'n2-b: double across gravity'),
    ('triple_normal', 1, 282300, 285200, 3, 'n7-b: triple'),
    ('double_normal', 1, 295000, 297500, 2, 'n7-c: double'),
    ('table_triple', 0, 871000, 873900, 0, 'n3: three knocks on the table 10-15 cm away'),
    ('table_double_hard', 0, 889800, 892500, 0, 'n3: hard double knock on the table 5 cm away'),
    ('object_put_down', 0, 901800, 903800, 0, 'n3: an object put down next to the device'),
    ('handling_volume', 1, 0, 0, 0, 'placeholder'),
]
# The handling excerpt is from boot 0 (n4: picked up, volume changed, put back).
EXCERPTS[-1] = ('handling_volume', 0, 945700, 949350, 0, 'n4: picked up, volume changed, put back')
EXCERPTS += [
    ('four_taps_handling', 1, 164500, 169600, 0, 'n6: taps while handling the device, then two taps'),
    ('pocket_walk', 0, 1051100, 1063100, 0, 'n5: carried in a pocket/bag while walking (12 s)'),
]


def load(path):
    rows = []
    with open(path) as f:
        for r in csv.DictReader(f):
            rows.append((r['seg'], int(r['idx']), float(r['t_ms']), int(r['x']), int(r['y']), int(r['z'])))
    return rows


def main():
    boots = [load(sys.argv[1]), load(sys.argv[2])]
    out = []
    out.append('// Generated by tests/generate_tap_fixtures.py from the BMI270 FIFO recordings')
    out.append('// of 2026-10-17 (tools/tap-eval/labels.csv). Do not edit.')
    out.append('#pragma once')
    out.append('#include <cstdint>')
    out.append('')
    out.append('namespace tap_fixtures {')
    out.append('struct Frame { int16_t x, y, z; };  // raw 400 Hz frames, 4096 LSB/g')
    out.append('struct Recording { const char *name; const Frame *frames; unsigned count; int expected; const char *comment; };')
    out.append('')
    table = []
    for name, boot, start, end, expected, comment in EXCERPTS:
        sel = [r for r in boots[boot] if start <= r[2] <= end]
        # Gap-free: a segment restart (screen state change) keeps the frames
        # contiguous in time, a lost frame would not.
        assert sel, name
        for a, b in zip(sel, sel[1:]):
            assert 2.0 < b[2] - a[2] < 3.2, (name, a, b)
        out.append(f'// {comment}: {len(sel)} frames from boot {boot} {start}..{end} ms')
        out.append(f'static const Frame {name}[] = {{')
        line = '   '
        for r in sel:
            item = f' {{{r[3]},{r[4]},{r[5]}}},'
            if len(line) + len(item) > 118:
                out.append(line)
                line = '   '
            line += item
        out.append(line)
        out.append('};')
        table.append(f'    {{"{name}", {name}, {len(sel)}u, {expected}, "{comment}"}},')
    out.append('')
    out.append('static const Recording recordings[] = {')
    out += table
    out.append('};')
    out.append('}  // namespace tap_fixtures')
    with open(sys.argv[3], 'w', newline='\n') as f:
        f.write('\n'.join(out) + '\n')
    print(f'{sys.argv[3]}: {len(table)} recordings')


if __name__ == '__main__':
    main()
